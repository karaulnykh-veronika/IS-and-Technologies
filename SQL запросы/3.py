# Эта функция определяет папку, где лежит наш скрипт
def get_script_folder():
    try:
        # __file__ — специальная переменная с путём к текущему файлу
        # Пример: C:\Users\Оля\Desktop\main.py
        script_path = os.path.abspath(__file__)
        # os.path.dirname() — обрезает имя файла, оставляя только папку
        # Пример: C:\Users\Оля\Desktop\main.py → C:\Users\Оля\Desktop
        folder = os.path.dirname(script_path)
        if folder:
            return folder
    except NameError:
        # Если __file__ не определён (например, в интерактивной среде)
        pass
    # Если ничего не получилось — используем текущую рабочую папку
    return os.getcwd()  # getcwd = get current working directory

# Получаем путь к папке со скриптом
current_folder = get_script_folder()
# os.chdir() — меняем рабочую директорию на эту папку
# Теперь все файлы будут создаваться именно здесь
os.chdir(current_folder)

# Печатаем путь, чтобы пользователь знал, куда сохранятся файлы
