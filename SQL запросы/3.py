# cursor() — создаёт курсор. Через курсор мы отправляем SQL команды в базу данных
cursor = conn.cursor()

# ============================================================
# СОЗДАНИЕ ТАБЛИЦ (SQL команды)
# ============================================================

# Таблица "уровни" (уровень образования: бакалавриат, магистратура и т.д.)
# id_ровня — первичный ключ (INTEGER PRIMARY KEY) — уникальный номер каждого уровня
# название — текстовое поле (TEXT NOT NULL) — не может быть пустым
cursor.execute("""
CREATE TABLE IF NOT EXISTS уровни (
    id_ровня INTEGER PRIMARY KEY NOT NULL UNIQUE,
    название TEXT NOT NULL
);
""")

# Таблица "направления" (специальности: Прикладная Информатика и т.д.)
cursor.execute("""
CREATE TABLE IF NOT EXISTS направления (
    id_направления INTEGER PRIMARY KEY NOT NULL UNIQUE,
    название TEXT NOT NULL
);
""")

# Таблица "типы" (форма обучения: очная, вечерняя, заочная)
cursor.execute("""
CREATE TABLE IF NOT EXISTS типы (
    id_типа INTEGER PRIMARY KEY NOT NULL UNIQUE,
    название TEXT NOT NULL
);
""")

# Таблица "студенты" — главная таблица
# FOREIGN KEY — внешние ключи, связывают эту таблицу с таблицами выше
# Это означает: у студента есть уровень обучения (ссылка на уровни),
# направление (ссылка на направления) и тип обучения (ссылка на типы)
cursor.execute("""
CREATE TABLE IF NOT EXISTS студенты (
    id_студента INTEGER PRIMARY KEY NOT NULL UNIQUE,
    id_уровня INTEGER NOT NULL,
    id_направления INTEGER NOT NULL,
    id_типа INTEGER NOT NULL,
    фамилия TEXT NOT NULL,
    имя TEXT NOT NULL,
    отчество TEXT,
    средний_балл REAL NOT NULL,
    FOREIGN KEY(id_уровня) REFERENCES уровни(id_ровня),
    FOREIGN KEY(id_направления) REFERENCES направления(id_направления),
    FOREIGN KEY(id_типа) REFERENCES типы(id_типа)
);
""")

print("✅ Таблицы созданы")

