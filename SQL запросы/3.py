# 6. ЗАПРОСЫ С CTE (Common Table Expressions)
# ============================================================
# CTE — это временная таблица, которая живёт только внутри запроса
# WITH — ключевое слово для создания CTE
print("\n" + "=" * 60)
print("ЗАПРОСЫ С CTE (Common Table Expressions)")
print("=" * 60)

# CTE 1: Создаём временную таблицу "топ_студенты" с 5 лучшими
# Потом просто выбираем всё из неё
query_cte1 = """
WITH топ_студенты AS (
    SELECT 
        s.фамилия,
        s.имя,
        s.средний_балл,
        н.название AS направление
    FROM студенты s
    JOIN направления н ON s.id_направления = н.id_направления
    ORDER BY s.средний_балл DESC
    LIMIT 5
)
SELECT * FROM топ_студенты
"""
print("\n1. Топ-5 студентов по среднему баллу (CTE с LIMIT):")
print(pd.read_sql(query_cte1, conn))

# CTE 2: Статистика по направлениям — считаем средний, макс, мин, количество
# Потом соединяем с таблицей направлений
query_cte2 = """
WITH статистика_направлений AS (
    SELECT 
        id_направления,
        ROUND(AVG(средний_балл), 2) AS средний_балл_направления,
        COUNT(*) AS количество_студентов,
        MAX(средний_балл) AS максимальный_балл,
        MIN(средний_балл) AS минимальный_балл
    FROM студенты
    GROUP BY id_направления
)
SELECT 
    н.название AS направление,
    сн.средний_балл_направления,
    сн.количество_студентов,
    сн.максимальный_балл,
    сн.минимальный_балл
FROM статистика_направлений сн
JOIN направления н ON сн.id_направления = н.id_направления
ORDER BY сн.средний_балл_направления DESC
"""
print("\n2. Статистика по направлениям (CTE с агрегацией):")
print(pd.read_sql(query_cte2, conn))

# CTE 3: Сначала находим всех отличников (балл >= 4.5)
# Потом считаем их количество по направлениям
query_cte3 = """
WITH отличники AS (
    SELECT 
        id_направления,
        фамилия,
        имя,
        средний_балл
    FROM студенты
    WHERE средний_балл >= 4.5
),
статистика_отличников AS (
    SELECT 
        о.id_направления,
        н.название AS направление,
        COUNT(*) AS количество_отличников,
        ROUND(AVG(о.средний_балл), 2) AS средний_балл_отличников
    FROM отличники о
    JOIN направления н ON о.id_направления = н.id_направления
    GROUP BY о.id_направления
)
SELECT * FROM статистика_отличников
ORDER BY количество_отличников DESC
"""
print("\n3. Количество отличников по направлениям (CTE с фильтрацией и агрегацией):")
print(pd.read_sql(query_cte3, conn))

# CTE 4: Несколько CTE в одном запросе
# Сначала создаём "очники" (студенты очной формы)
# Потом из них выбираем "высокий_балл" (балл >= 4.5)
# Затем группируем по направлениям
query_cte4 = """
WITH 
-- CTE 1: Студенты очной формы
очники AS (
    SELECT s.*, н.название AS направление
    FROM студенты s
    JOIN направления н ON s.id_направления = н.id_направления
    WHERE id_типа = 1
),
-- CTE 2: Студенты с высоким баллом (из очников)
высокий_балл AS (
    SELECT * FROM очники WHERE средний_балл >= 4.5
)
SELECT 
    направление,
    COUNT(*) AS количество_отличников_очников,
    ROUND(AVG(средний_балл), 2) AS средний_балл
FROM высокий_балл
GROUP BY направление
ORDER BY количество_отличников_очников DESC
"""
print("\n4. Отличники очной формы по направлениям (множественные CTE):")
print(pd.read_sql(query_cte4, conn))

