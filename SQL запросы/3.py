# 5. ЗАПРОСЫ С ПОДЗАПРОСАМИ
# ============================================================
# Подзапрос — это SQL запрос внутри другого SQL запроса
print("\n" + "=" * 60)
print("ЗАПРОСЫ С ПОДЗАПРОСАМИ")
print("=" * 60)

# Подзапрос 1: Сначала вычисляем средний балл всех студентов (в скобках)
# Потом выбираем тех, у кого балл выше этого среднего
query_sub1 = """
SELECT 
    фамилия,
    имя,
    средний_балл
FROM студенты
WHERE средний_балл > (SELECT AVG(средний_балл) FROM студенты)
ORDER BY средний_балл DESC
"""
print("\n1. Студенты с баллом выше среднего (подзапрос в WHERE):")
print(pd.read_sql(query_sub1, conn))

# Подзапрос 2: Находим направление с самым высоким средним баллом (подзапрос)
# Потом выбираем всех студентов этого направления
query_sub2 = """
SELECT 
    фамилия,
    имя,
    средний_балл
FROM студенты
WHERE id_направления = (
    SELECT id_направления 
    FROM студенты 
    GROUP BY id_направления 
    ORDER BY AVG(средний_балл) DESC 
    LIMIT 1
)
ORDER BY средний_балл DESC
"""
print("\n2. Студенты направления с самым высоким средним баллом:")
result_sub2 = pd.read_sql(query_sub2, conn)
print(result_sub2)

# Подзапрос 3: Коррелированный подзапрос — зависит от внешнего запроса
# Для каждого студента считаем средний балл по его направлению
# И сравниваем с баллом студента
query_sub3 = """
SELECT 
    s.фамилия,
    s.имя,
    н.название AS направление,
    s.средний_балл,
    (SELECT ROUND(AVG(средний_балл), 2) FROM студенты WHERE id_направления = s.id_направления) AS средний_балл_по_направлению
FROM студенты s
JOIN направления н ON s.id_направления = н.id_направления
WHERE s.средний_балл > (SELECT AVG(средний_балл) FROM студенты WHERE id_направления = s.id_направления)
ORDER BY н.название, s.средний_балл DESC
"""
print("\n3. Студенты с баллом выше среднего по своему направлению (коррелированный подзапрос):")
print(pd.read_sql(query_sub3, conn))

