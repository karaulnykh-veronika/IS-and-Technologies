# Формируем полный путь к файлу базы данных
db_path = os.path.join(current_folder, "students.db")

# sqlite3.connect() — открывает (или создаёт, если нет) файл базы данных
conn = sqlite3.connect(db_path)

# cursor() — создаёт курсор. Через курсор мы отправляем SQL команды в базу данных
cursor = conn.cursor()


# ----- СОЗДАНИЕ ТАБЛИЦЫ "Уровень_обучения" -----
# INTEGER PRIMARY KEY — целочисленный первичный ключ (уникальный ID)
# NOT NULL — поле не может быть пустым
# UNIQUE — значения не могут повторяться
cursor.execute("""
CREATE TABLE IF NOT EXISTS Уровень_обучения (
    айди_уровня INTEGER PRIMARY KEY NOT NULL UNIQUE,
    название VARCHAR NOT NULL
);
""")


# ----- СОЗДАНИЕ ТАБЛИЦЫ "Направления" -----
cursor.execute("""
CREATE TABLE IF NOT EXISTS Направления (
    айди_направления INTEGER PRIMARY KEY NOT NULL UNIQUE,
    название VARCHAR NOT NULL
);
""")


# ----- СОЗДАНИЕ ТАБЛИЦЫ "Типы_обучения" -----
cursor.execute("""
CREATE TABLE IF NOT EXISTS Типы_обучения (
    айди_типа INTEGER PRIMARY KEY NOT NULL UNIQUE,
    название VARCHAR NOT NULL
);
""")


# ----- СОЗДАНИЕ ТАБЛИЦЫ "Студенты" (главная таблица) -----
# FOREIGN KEY — внешний ключ, связывает эту таблицу с другими
# Это означает: у студента есть уровень (ссылка на Уровень_обучения),
# направление (ссылка на Направления) и тип обучения (ссылка на Типы_обучения)
cursor.execute("""
CREATE TABLE IF NOT EXISTS Студенты (
    айди_студента INTEGER PRIMARY KEY NOT NULL UNIQUE,
    айди_уровня INTEGER NOT NULL,
    айди_направления INTEGER NOT NULL,
    айди_типа_обучения INTEGER NOT NULL,
    фамилия VARCHAR NOT NULL,
    имя VARCHAR NOT NULL,
    отчество VARCHAR,
    средний_балл INTEGER NOT NULL,
    FOREIGN KEY (айди_уровня) REFERENCES Уровень_обучения(айди_уровня),
    FOREIGN KEY (айди_направления) REFERENCES Направления(айди_направления),
    FOREIGN KEY (айди_типа_обучения) REFERENCES Типы_обучения(айди_типа)
);
""")

