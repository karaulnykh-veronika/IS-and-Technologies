def get_script_folder():
    """
    Функция определяет папку, в которой находится текущий скрипт.
    Это нужно, чтобы все файлы (CSV, БД) создавались рядом с программой,
    а не в случайном месте.
    
    Возвращает: путь к папке в виде строки
    """
    try:
        # __file__ — специальная переменная, хранит полный путь к текущему файлу
        # Пример: C:\Users\Оля\Desktop\main.py
        script_path = os.path.abspath(__file__)
        # os.path.dirname() — обрезает имя файла, оставляя только папку
        # Пример: C:\Users\Оля\Desktop\main.py → C:\Users\Оля\Desktop
        folder = os.path.dirname(script_path)
        if folder:  # Если путь получен успешно
            return folder
    except NameError:
        # Если __file__ не определён (например, в интерактивной среде Jupyter)
        pass
    
    # Если ничего не получилось — используем текущую рабочую папку
    return os.getcwd()  # getcwd = get current working directory


