# ----- ЗАПРОС 2: Количество студентов по направлениям -----
# JOIN — соединяет таблицы Студенты и Направления по полю айди_направления
# GROUP BY — группирует записи по направлениям
# COUNT(*) — считает количество студентов в каждой группе
query2 = """
SELECT Направления.название AS Направление, COUNT(*) AS Количество
FROM Студенты
JOIN Направления ON Студенты.айди_направления = Направления.айди_направления
GROUP BY Студенты.айди_направления
"""
print("\n2. Количество студентов по направлениям:")
