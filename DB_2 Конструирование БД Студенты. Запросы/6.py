# ----- ЗАПРОС 4: Максимальный, минимальный и средний баллы по направлениям -----
# MAX() — максимальное значение
# MIN() — минимальное значение
# AVG() — среднее арифметическое
# ROUND(..., 2) — округление до 2 знаков после запятой
query4 = """
SELECT Направления.название AS Направление,
       MAX(средний_балл) AS Максимальный_балл,
       MIN(средний_балл) AS Минимальный_балл,
       ROUND(AVG(средний_балл), 2) AS Средний_балл
FROM Студенты
JOIN Направления ON Студенты.айди_направления = Направления.айди_направления
GROUP BY Студенты.айди_направления
"""
print("\n4. Максимальный, минимальный, средний баллы по направлениям:")
print(pd.read_sql(query4, conn))


# ----- ЗАПРОС 5: Средний балл по направлениям, уровням и формам обучения -----
# Группировка по трём полям одновременно
